func TestSharedRules(t *testing.T) {
	t.Run("expected rule count", func(t *testing.T) {
		assert.Len(t, SharedRules, 11)
	})

	t.Run("static rules match expected SQL", func(t *testing.T) {
		cases := []struct {
			sql  string
			want string
		}{
			{"CREATE DATABASE mydb", "CREATE DATABASE statements are unsupported"},
			{"CREATE EXTENSION pgcrypto", "CREATE EXTENSION statements are unsupported"},
			{"CREATE TRIGGER trg AFTER INSERT ON t", "CREATE TRIGGER statements are unsupported"},
			{"CREATE OR REPLACE TRIGGER trg AFTER INSERT ON t", "CREATE TRIGGER statements are unsupported"},
			{"CREATE TABLESPACE ts LOCATION '/data'", "CREATE TABLESPACE statements are unsupported"},
			{"CREATE MATERIALIZED VIEW mv AS SELECT 1", "CREATE MATERIALIZED VIEW or CREATE TABLE AS statements are unsupported"},
			{"CREATE TYPE address AS (street text)", "CREATE TYPE (composite types) statements are unsupported"},
			{"CREATE TEMPORARY TABLE tmp (id int)", "CREATE TEMPORARY TABLE is unsupported"},
			{"CREATE TEMP TABLE tmp (id int)", "CREATE TEMPORARY TABLE is unsupported"},
			{"CREATE TABLE child (extra text) INHERITS (parent)", "CREATE TABLE INHERITS is unsupported"},
			{"CREATE TABLE t (id int) PARTITION BY RANGE (id)", "CREATE TABLE PARTITION is unsupported"},
			{"TRUNCATE TABLE users", "TRUNCATE TABLE statements are unsupported"},
		}
		for _, tc := range cases {
			matched := false
			for _, r := range SharedRules {
				if msg := r.Match(tc.sql); msg != "" {
					assert.Equal(t, tc.want, msg, "sql: %s", tc.sql)
					matched = true
					break
				}
			}
			assert.True(t, matched, "expected match for: %s", tc.sql)
		}
	})

	t.Run("dynamic LANGUAGE rule", func(t *testing.T) {
		assert.Equal(t, "CREATE FUNCTION with language plpgsql not supported",
			SharedRules[len(SharedRules)-1].Match("CREATE FUNCTION f() RETURNS void LANGUAGE plpgsql AS $$ BEGIN END $$"))
		assert.Equal(t, "CREATE FUNCTION with language plv8 not supported",
			SharedRules[len(SharedRules)-1].Match("CREATE FUNCTION f() RETURNS void LANGUAGE plv8 AS $$ $$"))
	})

	t.Run("safe SQL does not match", func(t *testing.T) {
		safe := []string{
			"SELECT 1",
			"INSERT INTO users (id) VALUES ('1')",
			"CREATE TABLE t (id TEXT PRIMARY KEY)",
			"CREATE INDEX ASYNC idx ON t (col)",
			"CREATE FUNCTION add(a int, b int) RETURNS int LANGUAGE SQL AS 'SELECT a + b'",
		}
		for _, sql := range safe {
			for _, r := range SharedRules {
				assert.Empty(t, r.Match(sql), "rule %q should not match %q", r.Name, sql)
			}
		}
	})

	t.Run("case insensitive matching", func(t *testing.T) {
		assert.NotEmpty(t, SharedRules[0].Match("create database mydb"))
		assert.NotEmpty(t, SharedRules[0].Match("CREATE DATABASE mydb"))
	})
}

func TestStatementRules(t *testing.T) {
	match := func(sql string) []string {
		var msgs []string
		for _, r := range StatementRules {
			if msg := r.Match(sql); msg != "" {
				msgs = append(msgs, msg)
			}
		}
		return msgs
	}

	t.Run("violations", func(t *testing.T) {
		cases := map[string]string{
			"CREATE INDEX idx ON t (a)":                                          MsgIndexAsync,
			"CREATE INDEX ASYNC idx ON t (a DESC)":                               MsgIndexOrdering,
			"ALTER TABLE t ADD CHECK (a > 0)":                                    MsgAddConstraintValid,
			"ALTER TABLE t ADD CONSTRAINT f FOREIGN KEY (a) REFERENCES p":        MsgAddConstraintValid,
			"ALTER TABLE t ADD CONSTRAINT pk PRIMARY KEY (a)":                    MsgAddPrimaryKey,
			"ALTER TABLE t ADD UNIQUE (a)":                                       MsgAddUnique,
			"ALTER TABLE t ALTER COLUMN a TYPE text":                             MsgAlterColumnType,
			"ALTER TABLE t ALTER a SET NOT NULL":                                 MsgSetNotNull,
			"CREATE SEQUENCE s START 1":                                          MsgSequenceCache,
			"CREATE SEQUENCE s AS int CACHE 1":                                   MsgSequenceType,
			"CREATE SEQUENCE s CACHE 2":                                          MsgCacheRange,
			"CREATE SEQUENCE s CACHE 65535":                                      MsgCacheRange,
			"CREATE TABLE t (id int GENERATED BY DEFAULT AS IDENTITY (CACHE 1))": MsgIdentityType,
			"CREATE TABLE t (a bigint GENERATED ALWAYS AS IDENTITY (CACHE 1), b bigint GENERATED ALWAYS AS IDENTITY)": MsgIdentityCache,
		}
		for sql, want := range cases {
			assert.Equal(t, []string{want}, match(sql), "sql: %s", sql)
		}
	})

	t.Run("allowed", func(t *testing.T) {
		allowed := []string{
			"CREATE INDEX ASYNC idx ON t ((lower(a)), b NULLS FIRST) INCLUDE (c) NULLS NOT DISTINCT WHERE d IS NULL",
			"CREATE INDEX CONCURRENTLY idx ON t (a)", // reported by the CONCURRENTLY rule instead
			"ALTER TABLE t ADD CONSTRAINT c CHECK (a > 0) NOT VALID",
			"ALTER TABLE t ADD CONSTRAINT f FOREIGN KEY (a) REFERENCES p (id) NOT VALID",
			"ALTER TABLE t ADD CONSTRAINT u UNIQUE USING INDEX u",
			"ALTER TABLE t ADD COLUMN a int CHECK (a > 0)",
			"ALTER TABLE t ALTER COLUMN a SET DEFAULT 1",
			"ALTER TABLE t ALTER COLUMN int_col ADD GENERATED ALWAYS AS IDENTITY (CACHE 65536)",
			"CREATE SEQUENCE s CACHE 1",
			"CREATE SEQUENCE s CACHE 65536",
			"CREATE SEQUENCE s AS bigint CACHE 100000",
			"CREATE TABLE t (n integer CHECK (n > 0), id bigint GENERATED ALWAYS AS IDENTITY (CACHE 1))",
		}
		for _, sql := range allowed {
			assert.Empty(t, match(sql), "sql: %s", sql)
		}
	})
}

func TestSplit(t *testing.T) {
	t.Run("lines, comments, quotes, dollar bodies", func(t *testing.T) {
		sql := "-- header\nCREATE TABLE a (x int); /* block\ncomment */\n\nINSERT INTO a VALUES ('x;y', \"q;\");\nCREATE FUNCTION f() RETURNS int LANGUAGE SQL AS $body$ SELECT 1; $body$;\n  -- trailing"
		stmts := Split(sql)
		require.Len(t, stmts, 3)
		assert.Equal(t, Statement{Text: "CREATE TABLE a (x int)", Line: 2}, stmts[0])
		assert.Equal(t, Statement{Text: "INSERT INTO a VALUES ('x;y', \"q;\")", Line: 5}, stmts[1])
		assert.Equal(t, Statement{Text: "CREATE FUNCTION f() RETURNS int LANGUAGE SQL AS $body$ SELECT 1; $body$", Line: 6}, stmts[2])
	})

	t.Run("escaped quotes and positional params", func(t *testing.T) {
		stmts := Split("SELECT 'it''s; fine', $1; SELECT 2")
		require.Len(t, stmts, 2)
		assert.Equal(t, "SELECT 'it''s; fine', $1", stmts[0].Text)
	})

	t.Run("StripComments keeps code", func(t *testing.T) {
		assert.Equal(t, "CREATE INDEX idx ON t (a)", StripComments("-- note\nCREATE INDEX idx ON t (a) /* x */"))
	})
}
