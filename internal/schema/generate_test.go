func TestGenerateSequence(t *testing.T) {
	t.Run("create with defaults", func(t *testing.T) {
		seq := Sequence{Name: "s", Increment: 1, MinValue: 1, MaxValue: math.MaxInt64, Start: 1, Cache: 65536}
		assert.Equal(t, "CREATE SEQUENCE s CACHE 65536", generateCreateSequence(seq))
	})

	t.Run("create with options", func(t *testing.T) {
		seq := Sequence{Name: "s", Increment: 5, MinValue: 10, MaxValue: 1000, Start: 100, Cache: 1, Cycle: true}
		assert.Equal(t, "CREATE SEQUENCE s CACHE 1 INCREMENT BY 5 MINVALUE 10 MAXVALUE 1000 START WITH 100 CYCLE", generateCreateSequence(seq))
	})

	t.Run("alter only changed options", func(t *testing.T) {
		cur := Sequence{Name: "s", Increment: 1, MinValue: 1, MaxValue: math.MaxInt64, Start: 1, Cache: 1}
		des := cur
		des.Cache = 65536
		des.Cycle = true
		assert.Equal(t, "ALTER SEQUENCE s CACHE 65536 CYCLE", generateAlterSequence(cur, des))
		assert.Equal(t, "", generateAlterSequence(cur, cur))
	})

	t.Run("drop uses IF EXISTS", func(t *testing.T) {
		assert.Equal(t, "DROP SEQUENCE IF EXISTS s", generateDropSequence("s"))
	})

	t.Run("descending sequence defaults are omitted", func(t *testing.T) {
		seq := Sequence{Name: "d", Increment: -1, MinValue: math.MinInt64, MaxValue: -1, Start: -1, Cache: 1}
		assert.Equal(t, "CREATE SEQUENCE d CACHE 1 INCREMENT BY -1", generateCreateSequence(seq))
	})

	t.Run("alter every option", func(t *testing.T) {
		cur := Sequence{Name: "s", Increment: 1, MinValue: 1, MaxValue: 100, Start: 1, Cache: 1, Cycle: true}
		des := Sequence{Name: "s", Increment: 2, MinValue: 5, MaxValue: 200, Start: 7, Cache: 65536, Cycle: false}
		assert.Equal(t, "ALTER SEQUENCE s INCREMENT BY 2 MINVALUE 5 MAXVALUE 200 START WITH 7 CACHE 65536 NO CYCLE", generateAlterSequence(cur, des))
	})

	t.Run("owned by", func(t *testing.T) {
		assert.Equal(t, "ALTER SEQUENCE s OWNED BY t.id", generateSequenceOwnedBy(Sequence{Name: "s", OwnedBy: "t.id"}))
	})
}

