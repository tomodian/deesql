package schema

import (
	"context"
	"math"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestParse(t *testing.T) {
	t.Run("simple schema files", func(t *testing.T) {
		f := writeTemp(t, "users.sql", `
CREATE TABLE users (
    id   TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
    name TEXT NOT NULL
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		require.Len(t, out.Schema.Tables, 1)

		tbl := out.Schema.Tables[0]
		assert.Equal(t, "users", tbl.Name)
		assert.Len(t, tbl.Columns, 2)
		assert.Equal(t, "id", tbl.Columns[0].Name)
		assert.Equal(t, "text", tbl.Columns[0].Type)
		assert.False(t, tbl.Columns[0].IsNullable)
		assert.Equal(t, "gen_random_uuid()::TEXT", tbl.Columns[0].Default)
		require.NotNil(t, tbl.PrimaryKey)
		assert.Equal(t, []string{"id"}, tbl.PrimaryKey.Columns)
	})

	t.Run("multiple tables and indexes", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE orders (
    id     TEXT PRIMARY KEY,
    amount INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
);

CREATE INDEX ASYNC idx_orders_status ON orders (status);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		require.Len(t, out.Schema.Tables, 1)

		tbl := out.Schema.Tables[0]
		assert.Equal(t, "orders", tbl.Name)
		require.Len(t, tbl.Indexes, 1)
		assert.Equal(t, "idx_orders_status", tbl.Indexes[0].Name)
		assert.Equal(t, []string{"status"}, tbl.Indexes[0].Columns)
		assert.False(t, tbl.Indexes[0].IsUnique)
	})

	t.Run("unique index", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE items (
    id   TEXT PRIMARY KEY,
    code TEXT NOT NULL
);

CREATE UNIQUE INDEX ASYNC idx_items_code ON items (code);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		assert.True(t, out.Schema.Tables[0].Indexes[0].IsUnique)
	})

	t.Run("table-level constraints", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE events (
    id      TEXT NOT NULL,
    type    TEXT NOT NULL,
    payload TEXT,
    PRIMARY KEY (id),
    UNIQUE (type, id)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		tbl := out.Schema.Tables[0]
		require.NotNil(t, tbl.PrimaryKey)
		assert.Equal(t, []string{"id"}, tbl.PrimaryKey.Columns)
		require.Len(t, tbl.UniqueConstraints, 1)
		assert.Equal(t, []string{"type", "id"}, tbl.UniqueConstraints[0].Columns)
	})

	t.Run("named constraints", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE products (
    id    TEXT NOT NULL,
    name  TEXT NOT NULL,
    price INTEGER NOT NULL,
    CONSTRAINT products_pk PRIMARY KEY (id),
    CONSTRAINT products_name_uniq UNIQUE (name),
    CONSTRAINT products_price_positive CHECK (price > 0)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		tbl := out.Schema.Tables[0]
		require.NotNil(t, tbl.PrimaryKey)
		assert.Equal(t, "products_pk", tbl.PrimaryKey.Name)
		require.Len(t, tbl.UniqueConstraints, 1)
		assert.Equal(t, "products_name_uniq", tbl.UniqueConstraints[0].Name)
		require.Len(t, tbl.CheckConstraints, 1)
		assert.Equal(t, "products_price_positive", tbl.CheckConstraints[0].Name)
	})

	t.Run("identity columns", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE counters (
    id   INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY,
    name TEXT NOT NULL,
    PRIMARY KEY (id)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		col := out.Schema.Tables[0].Columns[0]
		assert.True(t, col.IsIdentity)
		assert.Equal(t, "ALWAYS", col.IdentityGeneration)
	})

	t.Run("by default identity", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE seq (
    id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (id)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		col := out.Schema.Tables[0].Columns[0]
		assert.True(t, col.IsIdentity)
		assert.Equal(t, "BY DEFAULT", col.IdentityGeneration)
	})

	t.Run("multi-word types", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE times (
    id TEXT PRIMARY KEY,
    ts TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    dp DOUBLE PRECISION NOT NULL DEFAULT 0.0
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		cols := out.Schema.Tables[0].Columns
		assert.Equal(t, "timestamptz", cols[1].Type)
		assert.Equal(t, "double precision", cols[2].Type)
	})

	t.Run("comments are stripped", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
-- This is a comment
CREATE TABLE t1 (
    -- This column comment should be ignored
    id TEXT PRIMARY KEY
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		assert.Len(t, out.Schema.Tables, 1)
	})

	t.Run("multiple files", func(t *testing.T) {
		f1 := writeTemp(t, "a.sql", `CREATE TABLE a (id TEXT PRIMARY KEY);`)
		f2 := writeTemp(t, "b.sql", `CREATE TABLE b (id TEXT PRIMARY KEY);`)

		out, err := Parse(context.Background(), ParseInput{Files: []string{f1, f2}})
		require.NoError(t, err)
		assert.Len(t, out.Schema.Tables, 2)
	})

	t.Run("unsupported statement returns error", func(t *testing.T) {
		f := writeTemp(t, "bad.sql", `ALTER TABLE users ADD COLUMN x TEXT;`)

		_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "unsupported statement")
	})

	t.Run("index on unknown table returns error", func(t *testing.T) {
		f := writeTemp(t, "bad.sql", `
CREATE TABLE t1 (id TEXT PRIMARY KEY);

CREATE INDEX ASYNC idx_missing ON missing_table (id);
`)
		_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "unknown table")
	})

	t.Run("validation error on empty input", func(t *testing.T) {
		_, err := Parse(context.Background(), ParseInput{Files: []string{}})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "invalid parse input")
	})

	t.Run("inline check constraint", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE items (
    id     TEXT PRIMARY KEY,
    status TEXT NOT NULL CHECK (status IN ('a', 'b'))
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		tbl := out.Schema.Tables[0]
		require.Len(t, tbl.CheckConstraints, 1)
		assert.Contains(t, tbl.CheckConstraints[0].Expression, "status")
	})

	t.Run("fixture files in tests/simple", func(t *testing.T) {
		fixtureDir := filepath.Join("..", "..", "tests", "simple")
		if _, err := os.Stat(fixtureDir); os.IsNotExist(err) {
			t.Skip("fixture directory not found")
		}

		matches, err := filepath.Glob(filepath.Join(fixtureDir, "*.sql"))
		require.NoError(t, err)
		require.NotEmpty(t, matches)

		out, err := Parse(context.Background(), ParseInput{Files: matches})
		require.NoError(t, err)
		assert.Len(t, out.Schema.Tables, 3)
	})

	t.Run("column with NULL keyword", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id TEXT PRIMARY KEY,
    name TEXT NULL
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		col := out.Schema.Tables[0].Columns[1]
		assert.True(t, col.IsNullable)
	})

	t.Run("inline unique constraint", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id TEXT PRIMARY KEY,
    code TEXT NOT NULL UNIQUE
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		tbl := out.Schema.Tables[0]
		require.Len(t, tbl.UniqueConstraints, 1)
		assert.Equal(t, []string{"code"}, tbl.UniqueConstraints[0].Columns)
	})

	t.Run("table-level check constraint", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id TEXT PRIMARY KEY,
    val INTEGER NOT NULL,
    CHECK (val > 0)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		tbl := out.Schema.Tables[0]
		require.Len(t, tbl.CheckConstraints, 1)
	})

	t.Run("column with varchar type", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id TEXT PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		col := out.Schema.Tables[0].Columns[1]
		assert.Equal(t, "varchar(255)", col.Type)
	})

	t.Run("unsupported named constraint type", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id TEXT NOT NULL,
    CONSTRAINT t_ex EXCLUDE USING btree (id WITH =)
);
`)
		_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "unsupported constraint type")
	})

	t.Run("empty sql file", func(t *testing.T) {
		f := writeTemp(t, "empty.sql", `-- just a comment`)

		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		assert.Empty(t, out.Schema.Tables)
	})

	t.Run("long unsupported statement gets truncated in error", func(t *testing.T) {
		longStmt := "INSERT INTO some_very_long_table_name_that_goes_on_and_on (col1, col2, col3, col4, col5) VALUES (1, 2, 3, 4, 5)"
		f := writeTemp(t, "bad.sql", longStmt+";")

		_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "...")
	})

	t.Run("foreign keys: inline, table-level, named, actions", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE users (
    id BIGINT PRIMARY KEY
);
CREATE TABLE orders (
    id        BIGINT PRIMARY KEY,
    user_id   BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
    buyer_id  BIGINT CONSTRAINT orders_buyer_fk REFERENCES users(id) ON UPDATE SET NULL DEFERRABLE INITIALLY DEFERRED,
    parent_id BIGINT,
    a BIGINT, b BIGINT,
    FOREIGN KEY(parent_id) REFERENCES orders (id) MATCH FULL ON DELETE SET NULL (parent_id),
    CONSTRAINT orders_pair_fk FOREIGN KEY (a, b) REFERENCES pairs (x, y) ON DELETE NO ACTION ON UPDATE RESTRICT
);
CREATE TABLE pairs (
    x BIGINT, y BIGINT,
    UNIQUE NULLS NOT DISTINCT (x, y)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		orders := out.Schema.Tables[1]
		require.Len(t, orders.ForeignKeys, 4)

		assert.Equal(t, ForeignKey{Name: "orders_user_id_fkey", Columns: []string{"user_id"}, RefTable: "users", RefColumns: []string{"id"}, OnDelete: "CASCADE"}, orders.ForeignKeys[0])
		assert.Equal(t, ForeignKey{Name: "orders_buyer_fk", Columns: []string{"buyer_id"}, RefTable: "users", RefColumns: []string{"id"}, OnUpdate: "SET NULL", Deferrable: true, InitiallyDeferred: true}, orders.ForeignKeys[1])
		assert.Equal(t, ForeignKey{Name: "orders_parent_id_fkey", Columns: []string{"parent_id"}, RefTable: "orders", RefColumns: []string{"id"}, OnDelete: "SET NULL (parent_id)", MatchFull: true}, orders.ForeignKeys[2])
		assert.Equal(t, ForeignKey{Name: "orders_pair_fk", Columns: []string{"a", "b"}, RefTable: "pairs", RefColumns: []string{"x", "y"}, OnUpdate: "RESTRICT"}, orders.ForeignKeys[3])

		// NOT NULL after REFERENCES on the same column still applies.
		assert.False(t, orders.Columns[1].IsNullable)

		pairs := out.Schema.Tables[2]
		require.Len(t, pairs.UniqueConstraints, 1)
		assert.True(t, pairs.UniqueConstraints[0].NullsNotDistinct)
	})

	t.Run("foreign key to unknown table returns error", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `CREATE TABLE t (id TEXT REFERENCES other(id));`)
		_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "references unknown table other")
	})

	t.Run("generated stored column and identity options", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id    BIGINT GENERATED ALWAYS AS IDENTITY (CACHE 70000),
    id2   BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 10 CACHE 1),
    a     INTEGER,
    total INTEGER GENERATED ALWAYS AS (a * 2) STORED
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		cols := out.Schema.Tables[0].Columns
		assert.True(t, cols[0].IsIdentity)
		assert.False(t, cols[0].IsNullable)
		assert.Equal(t, "CACHE 70000", cols[0].IdentityOptions)
		assert.Equal(t, "BY DEFAULT", cols[1].IdentityGeneration)
		assert.Equal(t, "START WITH 10 CACHE 1", cols[1].IdentityOptions)
		assert.False(t, cols[3].IsIdentity)
		assert.Equal(t, "(a * 2)", cols[3].Generated)
	})

	t.Run("primary key columns are not null and check names are deduplicated", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    a TEXT,
    b TEXT,
    PRIMARY KEY (a) INCLUDE (b),
    CHECK (a <> ''),
    CHECK (b <> '')
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		tbl := out.Schema.Tables[0]
		assert.False(t, tbl.Columns[0].IsNullable)
		assert.Equal(t, []string{"a"}, tbl.PrimaryKey.Columns)
		require.Len(t, tbl.CheckConstraints, 2)
		assert.Equal(t, "t_check", tbl.CheckConstraints[0].Name)
		assert.Equal(t, "t_check1", tbl.CheckConstraints[1].Name)
	})

	t.Run("expression, partial, and NULLS NOT DISTINCT indexes", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE UNIQUE INDEX ASYNC IF NOT EXISTS idx_email ON users ((lower(email)), tenant_id NULLS FIRST)
    INCLUDE (name)
    NULLS NOT DISTINCT
    WHERE deleted_at IS NULL;
CREATE TABLE users (email TEXT, tenant_id TEXT, name TEXT, deleted_at TIMESTAMPTZ);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		require.Len(t, out.Schema.Tables[0].Indexes, 1)
		assert.Equal(t, Index{
			Name:             "idx_email",
			Columns:          []string{"(lower(email))", "tenant_id nulls first"},
			IncludeColumns:   []string{"name"},
			IsUnique:         true,
			NullsNotDistinct: true,
			Where:            "deleted_at IS NULL",
		}, out.Schema.Tables[0].Indexes[0])
	})

	t.Run("CREATE INDEX without ASYNC returns error", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (a TEXT);
CREATE INDEX idx ON t (a);
`)
		_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.Error(t, err)
		assert.Contains(t, err.Error(), "must use ASYNC")
	})

	t.Run("statistics", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (a INT, b INT);
CREATE STATISTICS IF NOT EXISTS s_ab (ndistinct, dependencies) ON a, b FROM t;
CREATE STATISTICS s_all ON a, (b + 1) FROM public.t;
CREATE STATISTICS s_expr ON (a * b) FROM t;
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		stats := out.Schema.Tables[0].Statistics
		require.Len(t, stats, 3)
		assert.Equal(t, Statistics{Name: "s_ab", Kinds: []string{"dependencies", "ndistinct"}, Expressions: []string{"a", "b"}}, stats[0])
		assert.Equal(t, Statistics{Name: "s_all", Kinds: []string{"dependencies", "mcv", "ndistinct"}, Expressions: []string{"a", "(b + 1)"}}, stats[1])
		assert.Equal(t, Statistics{Name: "s_expr", Expressions: []string{"(a * b)"}}, stats[2])
	})

	t.Run("sequences", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (id BIGINT DEFAULT nextval('order_seq'));
CREATE SEQUENCE IF NOT EXISTS order_seq CACHE 65536;
CREATE SEQUENCE public.down_seq AS bigint INCREMENT BY -1 MAXVALUE 100 NO CYCLE CACHE 1 OWNED BY public.t.id;
CREATE SEQUENCE ranged CACHE 1 INCREMENT 5 MINVALUE 10 MAXVALUE 1000 START WITH 50 CYCLE;
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		require.Len(t, out.Schema.Sequences, 3)
		assert.Equal(t, Sequence{Name: "order_seq", Increment: 1, MinValue: 1, MaxValue: math.MaxInt64, Start: 1, Cache: 65536}, out.Schema.Sequences[0])
		assert.Equal(t, Sequence{Name: "down_seq", Increment: -1, MinValue: math.MinInt64, MaxValue: 100, Start: 100, Cache: 1, OwnedBy: "t.id"}, out.Schema.Sequences[1])
		assert.Equal(t, Sequence{Name: "ranged", Increment: 5, MinValue: 10, MaxValue: 1000, Start: 50, Cache: 1, Cycle: true}, out.Schema.Sequences[2])
	})

	t.Run("unmanaged statements are skipped, including bodies with semicolons", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (a INT);
CREATE FUNCTION f() RETURNS INT LANGUAGE SQL AS $$ SELECT 1; $$;
ALTER SYSTEM SET dsql.enable_batched_nestloop = off;
ALTER DEFAULT PRIVILEGES GRANT SELECT ON TABLES TO reader;
COMMENT ON TABLE t IS 'has; semicolon';
GRANT SELECT ON t TO reader;
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		require.Len(t, out.Schema.Tables, 1)
	})

	t.Run("default with function call", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
    ts TIMESTAMPTZ NOT NULL DEFAULT now()
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)

		assert.Equal(t, "gen_random_uuid()::TEXT", out.Schema.Tables[0].Columns[0].Default)
		assert.Equal(t, "now()", out.Schema.Tables[0].Columns[1].Default)
	})

	t.Run("parse errors for new statement types", func(t *testing.T) {
		cases := map[string]string{
			"CREATE TABLE t (a INT); CREATE TABLE t (a INT);":                                             "defined more than once",
			"CREATE STATISTICS s ON a, b FROM missing;":                                                   "statistics s references unknown table missing",
			"CREATE TABLE p (a INT); CREATE TABLE c (x INT REFERENCES p);":                                "has no primary key",
			"CREATE TABLE p (id INT PRIMARY KEY); CREATE TABLE c (x INT REFERENCES p ON DELETE EXPLODE);": "unsupported referential action",
			"CREATE SEQUENCE s CACHE lots;":                                                               "invalid number",
			"CREATE SEQUENCE s CACHE 1 FROBNICATE;":                                                       "unsupported option",
			"CREATE TABLE t (a INT); CREATE INDEX ASYNC i ON t (a) TABLESPACE fast;":                      "unsupported index clause",
			"CREATE TABLE t (a INT); CREATE INDEX ASYNC i ON t (a) INCLUDE b;":                            "parsing INCLUDE",
			"CREATE TABLE t (a INT); CREATE INDEX ASYNC i ON t (a;":                                       "parsing index i",
			"CREATE STATISTICS s;":                                                                        "unsupported statement",
		}
		for sql, want := range cases {
			f := writeTemp(t, "schema.sql", sql)
			_, err := Parse(context.Background(), ParseInput{Files: []string{f}})
			require.Error(t, err, "sql: %s", sql)
			assert.Contains(t, err.Error(), want, "sql: %s", sql)
		}
	})

	t.Run("index options: NULLS DISTINCT, WITH, schema-qualified table", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (a INT);
CREATE INDEX ASYNC i ON public.t (A) NULLS DISTINCT WITH (fillfactor = 90);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		assert.Equal(t, Index{Name: "i", Columns: []string{"a"}}, out.Schema.Tables[0].Indexes[0])
	})

	t.Run("foreign key options: MATCH SIMPLE, NOT DEFERRABLE, INITIALLY IMMEDIATE, SET DEFAULT", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE p (id INT PRIMARY KEY);
CREATE TABLE c (
    x INT DEFAULT 0 REFERENCES p MATCH SIMPLE ON DELETE SET DEFAULT ON UPDATE NO ACTION NOT DEFERRABLE INITIALLY IMMEDIATE NOT NULL
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		c := out.Schema.Tables[1]
		assert.Equal(t, ForeignKey{Name: "c_x_fkey", Columns: []string{"x"}, RefTable: "p", RefColumns: []string{"id"}, OnDelete: "SET DEFAULT"}, c.ForeignKeys[0])
		assert.Equal(t, "0", c.Columns[0].Default)
		assert.False(t, c.Columns[0].IsNullable)
	})

	t.Run("named inline constraints", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `
CREATE TABLE t (
    id   BIGINT CONSTRAINT t_id_pk PRIMARY KEY,
    code TEXT CONSTRAINT t_code_uq UNIQUE NULLS NOT DISTINCT,
    n    INT CONSTRAINT t_n_pos CHECK(n > 0)
);
`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		tbl := out.Schema.Tables[0]
		assert.Equal(t, "t_id_pk", tbl.PrimaryKey.Name)
		assert.Equal(t, UniqueConstraint{Name: "t_code_uq", Columns: []string{"code"}, NullsNotDistinct: true}, tbl.UniqueConstraints[0])
		assert.Equal(t, CheckConstraint{Name: "t_n_pos", Expression: "(n > 0)"}, tbl.CheckConstraints[0])
	})

	t.Run("sequence NO MINVALUE / NO MAXVALUE and OWNED BY NONE", func(t *testing.T) {
		f := writeTemp(t, "schema.sql", `CREATE SEQUENCE s NO MINVALUE NO MAXVALUE CACHE 1 OWNED BY NONE;`)
		out, err := Parse(context.Background(), ParseInput{Files: []string{f}})
		require.NoError(t, err)
		assert.Equal(t, Sequence{Name: "s", Increment: 1, MinValue: 1, MaxValue: math.MaxInt64, Start: 1, Cache: 1}, out.Schema.Sequences[0])
	})
}

func writeTemp(t *testing.T, name, content string) string {
	t.Helper()
	dir := t.TempDir()
	p := filepath.Join(dir, name)
	err := os.WriteFile(p, []byte(content), 0644)
	require.NoError(t, err)
	return p
}
